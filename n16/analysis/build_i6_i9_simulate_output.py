"""
Regenerates results_I6-I9_n16_simulate.json using the correctly
seeded (seed_simulator=42) simulation data, analogous to
build_i6_i11_output.py for the hardware-side files.

Why this exists: the results_I{6..9}_n16_simulate.json files
originally shipped in this package predate a seed_simulator=42 fix
and do not match paper_draft.tex's Table tab:results69 sim columns
(e.g. shipped I6 sim = [1.0, 1.0, 1.0, 0.9751], paper states
[0.9738, 1.0, 1.0, 0.9771]). The corrected, reproducible runs live in
a separate seed_sensitivity_test/ directory at the top level of the
project (results_I{6,7,8,9}_n16_simulate_SEEDED.json, generated by
qaoa_experiment_16_I{n}_seeded.py) and are copied in here as the
package's canonical source. I10 and I11's existing
results_I10/I11_n16_simulate.json files were already confirmed
correct and are untouched by this script.

Usage: run from this directory (n16/analysis/); the seeded source
files are read from the top-level project's seed_sensitivity_test/
folder (three levels up from this script), so this script is only
runnable inside the full project checkout, not from a standalone copy
of just the reproducibility_package -- see the note this prints if
the source files aren't found.
"""

import json
import os

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
RESULTS_DIR = os.path.join(SCRIPT_DIR, "..", "results")
SEEDED_SOURCE_DIR = os.path.join(SCRIPT_DIR, "..", "..", "..", "seed_sensitivity_test")

if not os.path.isdir(SEEDED_SOURCE_DIR):
    raise SystemExit(
        f"Seeded source directory not found at {SEEDED_SOURCE_DIR}.\n"
        "This script must be run from inside the full project checkout "
        "(it reads results_I{6,7,8,9}_n16_simulate_SEEDED.json from the "
        "top-level seed_sensitivity_test/ folder, which sits alongside "
        "this reproducibility_package, not inside it)."
    )

for inst in ["I6", "I7", "I8", "I9"]:
    src_path = os.path.join(SEEDED_SOURCE_DIR, f"results_{inst}_n16_simulate_SEEDED.json")
    with open(src_path) as f:
        seeded = json.load(f)

    out_path = os.path.join(RESULTS_DIR, f"results_{inst}_n16_simulate.json")
    with open(out_path, "w") as f:
        json.dump(seeded, f, indent=2)

    entry = seeded[0]
    sim = {k: v["approximation_ratio"] for k, v in entry["qaoa_sim"].items()}
    print(f"{inst}: wrote {out_path}")
    print(f"  sim (p=1..4) = {[round(sim[str(p)], 4) for p in [1,2,3,4]]}")
