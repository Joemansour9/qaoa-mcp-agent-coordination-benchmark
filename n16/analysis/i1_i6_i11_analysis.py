"""
Consolidated, current analysis for the extended simulation-ruggedness
predictor test (I1, I7, I8, I10, I11; n=5) reported in
Table tab:extended_predictor and Section sec:disc:noise:extended.

This REPLACES an earlier version of this file that (a) treated I8 as
ceilinged at p=2 and excluded it, working from only I1/I7/I10/I11
(n=4), and (b) used pre-rerun, untagged I6-I9 hardware data. Both
issues are corrected here by reading directly from:

  - Sim data: results_n16_simulate_seeded_2026-08-05.json (I1),
    results_I7/I8_n16_simulate.json (regenerated by
    build_i6_i9_simulate_output.py from the seed_simulator=42 source
    in seed_sensitivity_test/), results_I10/I11_n16_simulate.json
    (I10, I11, already current) -- all four read directly from file,
    nothing hardcoded.
  - Hardware p=2 data: results_I1_I4_rerun_2026-08-05.json (I1) and
    results_I{7,8,10,11}_n16_hardware.json (regenerated by
    build_i6_i11_output.py from the tagged rerun manifest).
  - Density and CV: computed directly from the symmetrized cost
    matrices in ../cost_matrices/ (same (W + W.T) / 2, off-diagonal
    upper-triangle convention as density_cv_verified.json), not
    hardcoded from the paper's printed table.

Reproduces the paper's exact printed numbers for all three tested
predictors against Delta_r_bar (Section sec:disc:noise:extended):
  R:       r_s=-0.300 (mean, exact p=0.683), r_s=+0.100 (median,
           exact p=0.950), r_s=-0.100 (best-of-three, exact p=0.950)
  Density: r_s=-0.300 (mean, exact p=0.683), r_s=-0.100 (median,
           exact p=0.950), r_s=-0.400 (best-of-three, exact p=0.517)
  CV:      r_s=+0.600 (mean, exact p=0.350), r_s=+0.200 (median,
           exact p=0.783), r_s=+0.300 (best-of-three, exact p=0.683)
and the pairwise redundancy checks: CV vs R r_s=-0.900 (exact
p=0.083), Density vs R r_s=+0.700 (exact p=0.233).
"""

import itertools
import json
import os

import numpy as np
import pandas as pd
from scipy.stats import spearmanr, pearsonr

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
RESULTS_DIR = os.path.join(SCRIPT_DIR, "..", "results")
COST_MATRIX_DIR = os.path.join(SCRIPT_DIR, "..", "cost_matrices")

INSTANCES = ["I1", "I7", "I8", "I10", "I11"]


def load_hw_p2(inst, path):
    with open(path) as f:
        d = json.load(f)
    entry = d[0]
    return [r["approximation_ratio"] for r in entry["qaoa_hw"]["2"]]


def load_sim(inst, path):
    with open(path) as f:
        d = json.load(f)
    entry = d[0]
    sim = entry["qaoa_sim"]
    return {int(k): v["approximation_ratio"] for k, v in sim.items()}


# ---- Sim data (approximation ratio, p=1..4) ----
sim = {}

with open(os.path.join(RESULTS_DIR, "results_n16_simulate_seeded_2026-08-05.json")) as f:
    n16_sim = json.load(f)
i1_entry = [r for r in n16_sim if r["instance"] == "I1_full_graph"][0]
sim["I1"] = {int(k): v["approximation_ratio"] for k, v in i1_entry["qaoa_sim"].items()}

sim["I7"] = load_sim("I7", os.path.join(RESULTS_DIR, "results_I7_n16_simulate.json"))
sim["I8"] = load_sim("I8", os.path.join(RESULTS_DIR, "results_I8_n16_simulate.json"))
sim["I10"] = load_sim("I10", os.path.join(RESULTS_DIR, "results_I10_n16_simulate.json"))
sim["I11"] = load_sim("I11", os.path.join(RESULTS_DIR, "results_I11_n16_simulate.json"))

# ---- Hardware p=2 data (3 tagged repeats each) ----
hw_p2 = {}

with open(os.path.join(RESULTS_DIR, "results_I1_I4_rerun_2026-08-05.json")) as f:
    i1_i4 = json.load(f)
hw_p2["I1"] = i1_i4["instances"]["I1"]["hw_runs"]["2"]

for inst in ["I7", "I8", "I10", "I11"]:
    hw_p2[inst] = load_hw_p2(inst, os.path.join(RESULTS_DIR, f"results_{inst}_n16_hardware.json"))

# ---- R = (max_p - min_p) / mean_p, over p=1..4 ----
R = {}
for inst in INSTANCES:
    vals = [sim[inst][p] for p in [1, 2, 3, 4]]
    R[inst] = (max(vals) - min(vals)) / np.mean(vals)

# ---- Density and CV, computed directly from the symmetrized cost matrices ----
COST_MATRIX_FILE = {
    "I1": "mcp_agent_data_16_cost_matrix.csv",
    "I7": "mcp_agent_data_16_I7_cost_matrix.csv",
    "I8": "mcp_agent_data_16_I8_cost_matrix.csv",
    "I10": "mcp_agent_data_16_I10_cost_matrix.csv",
    "I11": "mcp_agent_data_16_I11_cost_matrix.csv",
}


def load_symmetrized(path):
    df = pd.read_csv(path, index_col=0)
    W = df.values.astype(float)
    return (W + W.T) / 2


def density_and_cv(W):
    n = W.shape[0]
    vals = [W[i][j] for i in range(n) for j in range(i + 1, n) if W[i][j] > 0]
    n_possible = n * (n - 1) // 2
    return len(vals) / n_possible, float(np.std(vals) / np.mean(vals))


density, cv = {}, {}
for inst in INSTANCES:
    W = load_symmetrized(os.path.join(COST_MATRIX_DIR, COST_MATRIX_FILE[inst]))
    density[inst], cv[inst] = density_and_cv(W)

# ---- Delta_r_bar at p=2, three definitions ----
def best_of_three(vals):
    return max(vals)


defs = {"mean": np.mean, "median": np.median, "best_of_3": best_of_three}
delta = {d: {} for d in defs}
for inst in INSTANCES:
    for dname, fn in defs.items():
        delta[dname][inst] = float(fn(hw_p2[inst])) - sim[inst][2]


def exact_perm_pvalue(x, y):
    n = len(x)
    obs_rho, _ = spearmanr(x, y)
    count = 0
    total = 0
    for perm in itertools.permutations(range(n)):
        y_perm = [y[i] for i in perm]
        rho, _ = spearmanr(x, y_perm)
        total += 1
        if abs(rho) >= abs(obs_rho) - 1e-12:
            count += 1
    return obs_rho, count / total


print("=" * 90)
print("R (simulation ruggedness), I1/I7/I8/I10/I11")
print("=" * 90)
for inst in INSTANCES:
    print(f"{inst}: sim={[round(sim[inst][p], 4) for p in [1,2,3,4]]}  R={R[inst]:.6f}")

print()
print("=" * 90)
print("Delta_r_bar at p=2, three definitions")
print("=" * 90)
for inst in INSTANCES:
    print(f"{inst}: hw_p2={[round(v,4) for v in hw_p2[inst]]}  sim_p2={sim[inst][2]:.4f}  "
          f"delta(mean)={delta['mean'][inst]:+.4f}  delta(median)={delta['median'][inst]:+.4f}  "
          f"delta(best3)={delta['best_of_3'][inst]:+.4f}")

print()
print("=" * 90)
print("Density, CV (computed from raw cost matrices)")
print("=" * 90)
for inst in INSTANCES:
    print(f"{inst}: density={density[inst]:.4f}  cv={cv[inst]:.4f}")

print()
print("=" * 90)
print("Spearman [R | Density | CV] vs Delta_r_bar, exact permutation p-value (n=5, 5!=120 permutations)")
print("=" * 90)
results = {}
for feat_name, feat in [("R", R), ("Density", density), ("CV", cv)]:
    results[feat_name] = {}
    for dname in defs:
        x = [feat[i] for i in INSTANCES]
        y = [delta[dname][i] for i in INSTANCES]
        rho, p_exact = exact_perm_pvalue(x, y)
        rp, pp = pearsonr(x, y)
        results[feat_name][dname] = {"spearman_r": rho, "exact_p": p_exact, "pearson_r": rp, "pearson_p": pp}
        print(f"{feat_name:8s}{dname:10s}: r_s={rho:+.3f}  exact p={p_exact:.3f}   (Pearson r={rp:+.3f}, p={pp:.3f})")

print()
print("=" * 90)
print("Pairwise redundancy checks: CV vs R, Density vs R")
print("=" * 90)
pairwise = {}
for feat_name, feat in [("CV_vs_R", cv), ("Density_vs_R", density)]:
    x = [feat[i] for i in INSTANCES]
    y = [R[i] for i in INSTANCES]
    rho, p_exact = exact_perm_pvalue(x, y)
    rp, pp = pearsonr(x, y)
    pairwise[feat_name] = {"spearman_r": rho, "exact_p": p_exact, "pearson_r": rp, "pearson_p": pp}
    print(f"{feat_name:14s}: r_s={rho:+.3f}  exact p={p_exact:.3f}   (Pearson r={rp:+.3f}, p={pp:.3f})")

out = {
    "instances": INSTANCES,
    "sim": sim,
    "hw_p2": hw_p2,
    "R": R,
    "density": density,
    "cv": cv,
    "delta_r_bar_by_definition": delta,
    "spearman_vs_delta_r_bar": results,
    "pairwise_redundancy": pairwise,
}
out_path = os.path.join(SCRIPT_DIR, "i1_i6_i11_analysis.json")
with open(out_path, "w") as f:
    json.dump(out, f, indent=2, default=float)
print(f"\nSaved -> {out_path}")
